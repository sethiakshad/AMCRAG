"""Integration test verifying complete compatibility with Person 2 (Text Retrieval Subsystem).

Tests the exact handoff interface:
- Person 1 pipeline output chunks passed directly to retriever.index_knowledge_base()
- Standalone chunk_text.py JSON output loaded as schemas.DocumentChunk
- Payload preservation (section headings, page spans, citations)
- Deterministic IDs and Qdrant/BM25 payload constraints
"""

import json
from pathlib import Path
from typing import List
import pytest

from app.config import Settings
from app.services.pipeline import DocumentProcessingPipeline
from chunk_text import chunk_pdf
from schemas import DocumentChunk


class MockPerson2Retriever:
    """Mock simulating Person 2's HybridTextRetriever to verify Plug 1 ingestion contract."""

    def __init__(self):
        self.indexed_chunks: List[DocumentChunk] = []
        self.qdrant_points: List[dict] = []
        self.bm25_corpus: List[str] = []

    def index_knowledge_base(self, chunks: List[DocumentChunk]) -> int:
        """Simulate Person 2's exact ingestion method from Section 5 of OM_WORK.md."""
        for chunk in chunks:
            # Person 2 accesses these exact attributes
            assert isinstance(chunk.chunk_id, str) and chunk.chunk_id.strip()
            assert isinstance(chunk.document_id, str) and chunk.document_id.strip()
            assert isinstance(chunk.page_number, int) and chunk.page_number >= 1
            assert isinstance(chunk.text, str) and chunk.text.strip()
            assert isinstance(chunk.source_filename, str) and chunk.source_filename.strip()
            assert isinstance(chunk.page_start, int) and chunk.page_start >= 1
            assert isinstance(chunk.page_end, int) and chunk.page_end >= chunk.page_start

            # Person 2 Qdrant payload inspection
            payload = {
                "chunk_id": chunk.chunk_id,
                "document_id": chunk.document_id,
                "page_number": chunk.page_number,
                "page_start": chunk.page_start,
                "page_end": chunk.page_end,
                "source_filename": chunk.source_filename,
                "text": chunk.text,
                "metadata": chunk.metadata,
            }
            self.qdrant_points.append(payload)
            self.bm25_corpus.append(chunk.text)
            self.indexed_chunks.append(chunk)

        return len(chunks)


def test_person1_pipeline_to_person2_retriever_ingestion(sample_text_pdf: Path, test_settings: Settings):
    """Test that ProcessedDocumentOutput.chunks pass Person 2's ingestion hook."""
    pipeline = DocumentProcessingPipeline(settings=test_settings)
    output = pipeline.process_file(sample_text_pdf)

    assert output.status == "success"
    assert output.total_chunks > 0
    assert len(output.chunks) == output.total_chunks

    # Plug 1: Person 1 handoff to Person 2
    retriever = MockPerson2Retriever()
    count = retriever.index_knowledge_base(chunks=output.chunks)

    assert count == output.total_chunks
    assert len(retriever.indexed_chunks) == output.total_chunks

    # Verify first chunk attributes
    first = retriever.indexed_chunks[0]
    assert first.document_id == output.document_id
    assert first.source_filename == "sample_text.pdf"
    assert first.page_number == 1
    assert first.page_start == 1
    assert first.page_end == 1
    assert len(first.text) > 0
    # Rich metadata verification
    assert first.metadata["section"] is not None
    assert isinstance(first.metadata["headings"], list)
    assert first.metadata["table"] is False


def test_standalone_chunk_text_json_to_person2_document_chunks(sample_text_pdf: Path, tmp_path: Path):
    """Test that JSON generated by chunk_text.py deserializes into Person 2 DocumentChunks."""
    chunk_result = chunk_pdf(sample_text_pdf, chunk_size=300, chunk_overlap=50)

    assert chunk_result["total_chunks"] > 0
    json_path = tmp_path / "chunks_output.json"
    with json_path.open("w", encoding="utf-8") as f:
        json.dump(chunk_result, f, indent=2)

    with json_path.open("r", encoding="utf-8") as f:
        loaded_data = json.load(f)

    # Convert to Person 2 DocumentChunk list
    chunks: List[DocumentChunk] = [DocumentChunk(**c) for c in loaded_data["chunks"]]

    retriever = MockPerson2Retriever()
    indexed_count = retriever.index_knowledge_base(chunks=chunks)
    assert indexed_count == len(chunks)

    # Check that both Person 2 and Person 1 keys are accessible
    sample_chunk = chunks[0]
    assert sample_chunk.text == loaded_data["chunks"][0]["text"]
    assert sample_chunk.chunk_text == loaded_data["chunks"][0]["chunk_text"]
    assert sample_chunk.source_filename == "sample_text.pdf"
    assert sample_chunk.page_start == loaded_data["chunks"][0]["start_page"]
    assert sample_chunk.page_end == loaded_data["chunks"][0]["end_page"]
    assert sample_chunk.metadata["section"] is not None
